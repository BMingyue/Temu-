const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const context={module:{exports:{}},URL};
vm.runInNewContext(fs.readFileSync('./gpt_chrome_extension/content.js','utf8'),context);
const api=context.module.exports;
const task={job_id:'a'.repeat(32),workflow_mode:'single_image_chat_v1',step_number:3,step_token:'step-three',prompt_marker:'WBSTEP-a-three',attachments:[{name:'01-template.png'},{name:'02-reference.png'}]};
assert.equal(api.attachmentItems(task).length,2);
assert.equal(api.attachmentEvidence(task,{searchable:'',imageCount:2,thumbnailCount:2,uploading:false}).ready,true);
assert.equal(api.attachmentEvidence(task,{searchable:'',imageCount:1,thumbnailCount:1,uploading:false}).ready,false);
assert.equal(api.attachmentEvidence(task,{searchable:'',imageCount:2,thumbnailCount:2,uploading:true}).ready,false);
assert.equal(api.attachmentEvidence(task,{searchable:'',imageCount:3,thumbnailCount:3,uploading:false}).ready,false);
assert.equal(api.downloadTask(task,1).step,3);
assert.equal(api.downloadTask(task,1).step_token,'step-three');
const turn=(role,text,position)=>({role,textContent:text,position,getAttribute:key=>key==='data-message-id'?'msg-'+position:null,closest:()=>null,querySelectorAll:()=>[],compareDocumentPosition(other){return other.position>this.position?4:2}});
const oldUser=turn('user','old',0),oldAssistant=turn('assistant','old image',1),user=turn('user',task.prompt_marker,2),assistant=turn('assistant','new image',3);
let nodes=[oldUser,oldAssistant,user,assistant];
context.document={querySelectorAll:selector=>nodes.filter(n=>selector.includes('"'+n.role+'"'))};
assert.equal(api.workflowUserTurn(task),user);
assert.equal(api.workflowAssistantTurn(task),assistant);
const outerUser={...user,contains:other=>other===user};
nodes=[oldUser,oldAssistant,outerUser,user,assistant];
assert.equal(api.workflowUserTurn(task),user);
assert.equal(api.workflowAssistantTurn(task),assistant);
nodes.push(turn('user','manual message',4));
assert.throws(()=>api.workflowAssistantTurn(task),/另一条用户消息/);
nodes=[user,turn('user',task.prompt_marker,5)];
assert.throws(()=>api.workflowUserTurn(task),/重复用户消息/);
console.log('Workflow attachment order, step binding and response scope: OK');
